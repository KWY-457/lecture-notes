/** 搜索用：把一条问答压成可匹配的纯文本 */
function hay(item) {
  return (item.q + ' ' + item.a).toLowerCase();
}

/**
 * 过滤。
 *
 * 只看「问题 + 答案」，不看分组标题 —— 用户搜「401」不该因为分组叫
 * 「报错对照」而被整个留下（那等于没过滤）。
 * 空关键词返回全部；一条都不匹配时返回空数组，由调用方给「没找到」的提示。
 */
export function filterFaq(keyword, list = { errors: ERRORS, usage: USAGE }) {
  const kw = String(keyword || '').trim().toLowerCase();
  if (!kw) return { errors: list.errors, usage: list.usage };
  const pick = (arr) => arr.filter((it) => hay(it).includes(kw));
  return { errors: pick(list.errors), usage: pick(list.usage) };
}

/** 有多少条（给界面显示「共 N 条」，也方便测试钉住内容没被删空） */
export function faqCount(list = { errors: ERRORS, usage: USAGE }) {
  return list.errors.length + list.usage.length;
}

